/**
 * The text of the three files `ui:sync` writes:
 *
 * - `.strutvane/ui.gen.ts`: machine-owned, rewritten on every sync (typed names + metadata + the
 *   import map of owned files);
 * - `.strutvane/ui.lock.json`: machine-owned, the field names seen at the last sync, so the next
 *   sync can tell which columns are new;
 * - `resources/ui/<resource>.ui.ts`: developer-owned, written once when a table first appears.
 *
 * All output is deterministic (sorted, LF, no dates, no machine paths), so it is safe to commit
 * and to compare in tests.
 *
 * @module
 */
import { defaultColumns, defaultFilterFields, defaultFormFields } from '../shared/defaults.ts'
import { guessIcon } from '../shared/icons.ts'
import { visibleFields, type AppMetadata, type ResourceMetadata } from '../shared/metadata.ts'

/** Where the owned file of a resource lives, relative to the app root. */
export const OWNED_DIR = 'resources/ui'
/** Machine-owned registry, relative to the app root. */
export const GEN_FILE = '.strutvane/ui.gen.ts'
/** Machine-owned lock, relative to the app root. */
export const LOCK_FILE = '.strutvane/ui.lock.json'
/** The migrate output this generator reads, relative to the app root. */
export const RESOURCES_FILE = '.strutvane/resources.json'

/**
 * Path of a resource's owned file, relative to the app root. Uses the URL route (kebab-case), so
 * `invoice_lines` becomes `resources/ui/invoice-lines.ui.ts`.
 *
 * @example
 * ownedFilePath(posts) // 'resources/ui/posts.ui.ts'
 */
export function ownedFilePath(resource: ResourceMetadata): string {
  return `${OWNED_DIR}/${resource.route}.ui.ts`
}

/**
 * The field names an owned file may use for a resource: every field the API returns.
 *
 * @example
 * typedFieldNames(users) // ['id', 'name', 'email', 'created_at', 'updated_at'] (no 'password')
 */
export function typedFieldNames(resource: ResourceMetadata): string[] {
  return visibleFields(resource).map((field) => field.name)
}

/**
 * Render the scaffold of a new owned file. Everything is `auto()`, and a comment lists what
 * `auto()` resolves to today, so the developer can see the defaults before overriding them.
 *
 * @example
 * renderOwnedFile(posts) // "import { auto, defineResourceUi } from '#strutvane/ui'\n..."
 */
export function renderOwnedFile(resource: ResourceMetadata): string {
  const names = (fields: readonly { readonly name: string }[]): string => fields.map((field) => field.name).join(', ') || '(none)'
  return [
    `import { auto, defineResourceUi } from '#strutvane/ui'`,
    ``,
    `/**`,
    ` * How ${resource.label.plural.toLowerCase()} look in the admin UI. This file is yours: \`ui:sync\` wrote it once,`,
    ` * when the \`${resource.table}\` table first appeared, and never touches it again.`,
    ` *`,
    ` * \`auto()\` follows the schema: a column added by a later migration shows up by itself.`,
    ` * Replace it with a list (\`columns: ['title', 'status']\`) to take full control; from then on`,
    ` * \`ui:sync\` only reports new columns. Field names are type-checked against the schema.`,
    ` *`,
    ` * What auto() resolves to today:`,
    ` * - columns: ${names(defaultColumns(resource))}`,
    ` * - form:    ${names(defaultFormFields(resource))}`,
    ` * - filters: ${names(defaultFilterFields(resource))}`,
    ` */`,
    `export default defineResourceUi('${resource.table}', {`,
    `  columns: auto(),`,
    `  form: auto(),`,
    `  filters: auto(),`,
    `  navigation: { icon: '${guessIcon(resource.table)}' },`,
    `})`,
    ``,
  ].join('\n')
}

/**
 * One owned file the generated registry imports.
 *
 * @example
 * const owned: OwnedImport = { table: 'posts', path: 'resources/ui/posts.ui.ts' }
 */
export interface OwnedImport {
  readonly table: string
  readonly path: string
}

/**
 * Render `.strutvane/ui.gen.ts`.
 *
 * It holds three things: the {@link UiRegistry} augmentation (field names per resource, which is
 * what turns a dropped column into a type error), the metadata itself (so the app needs no extra
 * fetch to draw the sidebar), and static imports of the owned files that exist.
 *
 * @example
 * renderGenFile(metadata, [{ table: 'posts', path: 'resources/ui/posts.ui.ts' }])
 */
export function renderGenFile(metadata: AppMetadata, owned: readonly OwnedImport[]): string {
  const resources = [...metadata.resources].sort((a, b) => compareText(a.table, b.table))
  const imports = [...owned].sort((a, b) => compareText(a.table, b.table))
  const registryLines = resources.map((resource) => `    ${propertyKey(resource.table)}: ${unionOf(typedFieldNames(resource))}`)
  const importLines = imports.map((item) => `import ${importName(item.table)} from '../${item.path}'`)
  const ownedLines = imports.map((item) => `  ${propertyKey(item.table)}: ${importName(item.table)},`)
  return [
    `// Generated by \`ui:sync\` from ${RESOURCES_FILE}. Do not edit: every migrate rewrites this file.`,
    `// Your settings live in ${OWNED_DIR}/*.ui.ts, which ui:sync never overwrites.`,
    `import type { AppMetadata, ResourceUi } from '#strutvane/ui'`,
    ...importLines,
    ``,
    `declare module '#strutvane/ui' {`,
    `  /** Field names per resource: owned files are type-checked against these. */`,
    `  interface UiRegistry {`,
    ...registryLines,
    `  }`,
    `}`,
    ``,
    `/** Every resource name, as of the last migrate. */`,
    `export type GeneratedResourceName = ${unionOf(resources.map((resource) => resource.table))}`,
    ``,
    `/** The resource metadata the screens are rendered from. */`,
    `export const metadata: AppMetadata = ${JSON.stringify({ version: metadata.version, resources }, null, 2)}`,
    ``,
    `/** Developer-owned settings, by resource. A resource without a file uses the defaults. */`,
    `export const ownedUi: Readonly<Record<string, ResourceUi>> = {`,
    ...ownedLines,
    `}`,
    ``,
  ].join('\n')
}

/**
 * The lock written next to the registry: field names per resource at the last sync.
 *
 * @example
 * const lock: UiLock = { version: 1, resources: { posts: ['id', 'title'] } }
 */
export interface UiLock {
  readonly version: 1
  readonly resources: Readonly<Record<string, readonly string[]>>
}

/**
 * Render the lock file.
 *
 * @example
 * renderLock(metadata) // '{\n  "version": 1,\n  "resources": { ... }\n}\n'
 */
export function renderLock(metadata: AppMetadata): string {
  const resources: Record<string, string[]> = {}
  for (const resource of [...metadata.resources].sort((a, b) => compareText(a.table, b.table))) {
    resources[resource.table] = typedFieldNames(resource)
  }
  const lock: UiLock = { version: 1, resources }
  return `${JSON.stringify(lock, null, 2)}\n`
}

/**
 * Parse a lock file. A missing or damaged lock returns `undefined`, which only means "every table
 * looks new": safe, because owned files are never overwritten anyway.
 *
 * @example
 * parseLock('{"version":1,"resources":{}}') // { version: 1, resources: {} }
 * parseLock('garbage') // undefined
 */
export function parseLock(text: string | undefined): UiLock | undefined {
  if (text === undefined) return undefined
  try {
    const value: unknown = JSON.parse(text)
    if (typeof value !== 'object' || value === null || !('version' in value) || value.version !== 1 || !('resources' in value)) return undefined
    const resources = value.resources
    if (typeof resources !== 'object' || resources === null) return undefined
    const checked: Record<string, string[]> = {}
    for (const [table, fields] of Object.entries(resources)) {
      if (!Array.isArray(fields) || !fields.every((field: unknown) => typeof field === 'string')) return undefined
      checked[table] = fields
    }
    return { version: 1, resources: checked }
  } catch {
    return undefined
  }
}

/** `posts` → `postsUi`, `invoice_lines` → `invoiceLinesUi`: a valid, readable identifier. */
function importName(table: string): string {
  const camel = table.replace(/_([a-z0-9])/g, (_match, letter: string) => letter.toUpperCase())
  return `${camel}Ui`
}

/** Table names are validated SQL identifiers (spike 10), so they are also valid property keys. */
function propertyKey(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name)
}

function unionOf(names: readonly string[]): string {
  return names.length === 0 ? 'never' : names.map((name) => JSON.stringify(name).replace(/"/g, "'")).join(' | ')
}

/** Code-unit order: the same on every machine and locale, so output is byte-stable. */
function compareText(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0
}
