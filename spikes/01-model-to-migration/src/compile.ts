/**
 * Compiles ModelDefinitions into Drizzle table objects for Postgres and SQLite.
 *
 * Design rules (deliberate, see README "Design decisions"):
 * - Every constraint/index has a deterministic name derived from table + column, so
 *   snapshots of two model versions line up and the differ never sees spurious renames.
 *   The naming strategy is injectable so the migration planner can keep the names that
 *   already exist in the database after a table/column rename.
 * - enum fields compile to TEXT + a named CHECK constraint on both dialects. One portable
 *   representation, and no Postgres enum *types* (whose renames/drops drizzle-kit also
 *   resolves through interactive prompts).
 * - `decimal` is NUMERIC(p,s) on Postgres and TEXT on SQLite (SQLite NUMERIC affinity
 *   silently converts to floating point and loses precision).
 * - Primary keys are UUIDs generated by the application (UUIDv7), not by the database,
 *   so behaviour is identical on every engine and Postgres version.
 * - Foreign keys are declared as *named* table constraints (not column `.references()`),
 *   so their names are ours and stable.
 * - With `tenant: true`, unique fields are unique *per tenant*: UNIQUE(tenant_id, col).
 */
import { sql, type SQL } from 'drizzle-orm'
import * as pg from 'drizzle-orm/pg-core'
import * as lite from 'drizzle-orm/sqlite-core'
import { columnName, type FieldDef, type ModelDefinition } from './dsl.js'

const quote = (v: string): string => `'${v.replaceAll("'", "''")}'`

/** CHECK expression restricting an enum column to its allowed values. */
export const enumCheck = (col: string, values: readonly string[]): SQL =>
  sql.raw(`"${col}" IN (${values.map(quote).join(', ')})`)

export type ConstraintKind = 'unique' | 'index' | 'check' | 'fk' | 'tenantIndex'

/**
 * Naming strategy for constraints and indexes. The default derives names from the
 * current table/column. The migration planner passes a "legacy" strategy so that,
 * after a rename, the compiled *previous* schema still uses the names that exist in
 * the database; the differ then drops/creates the renamed constraints explicitly.
 */
export type Naming = (kind: ConstraintKind, table: string, column: string) => string

/** Deterministic default names. (Postgres truncates identifiers at 63 bytes; see README limits.) */
export const defaultNaming: Naming = (kind, table, column) => {
  switch (kind) {
    case 'unique':
      return `${table}_${column}_unique`
    case 'index':
      return `${table}_${column}_idx`
    case 'check':
      return `${table}_${column}_check`
    case 'fk':
      return `${table}_${column}_fk`
    case 'tenantIndex':
      return `${table}_tenant_id_idx`
  }
}

/** Convenience accessors for tests and docs. */
export const names = {
  unique: (table: string, col: string) => defaultNaming('unique', table, col),
  index: (table: string, col: string) => defaultNaming('index', table, col),
  check: (table: string, col: string) => defaultNaming('check', table, col),
  fk: (table: string, col: string) => defaultNaming('fk', table, col),
  tenantIndex: (table: string) => defaultNaming('tenantIndex', table, 'tenant_id'),
}

export interface CompileOptions {
  /** Constraint/index naming strategy. Defaults to {@link defaultNaming}. */
  readonly naming?: Naming
}

function assertTargets(models: readonly ModelDefinition[]): void {
  const byName = new Map(models.map((m) => [m.name, m]))
  if (byName.size !== models.length) throw new Error('Duplicate model names')
  const tables = new Set(models.map((m) => m.table))
  if (tables.size !== models.length) throw new Error('Two models map to the same table name')
  for (const m of models) {
    for (const [key, f] of Object.entries(m.fields)) {
      if (f.kind === 'belongsTo' && !byName.has(f.target ?? '')) {
        throw new Error(`${m.name}.${key} belongsTo unknown model "${f.target}"`)
      }
    }
  }
}

/** Orders models so that belongsTo targets come first. Throws on cycles (not supported in the spike). */
export function topoSort(models: readonly ModelDefinition[]): ModelDefinition[] {
  const byName = new Map(models.map((m) => [m.name, m]))
  const out: ModelDefinition[] = []
  const state = new Map<string, 'visiting' | 'done'>()
  const visit = (m: ModelDefinition, path: readonly string[]): void => {
    const s = state.get(m.name)
    if (s === 'done') return
    if (s === 'visiting') throw new Error(`Cyclic belongsTo chain: ${[...path, m.name].join(' -> ')}`)
    state.set(m.name, 'visiting')
    for (const f of Object.values(m.fields)) {
      if (f.kind === 'belongsTo' && f.target !== m.name) {
        const target = byName.get(f.target ?? '')
        if (target) visit(target, [...path, m.name])
      }
    }
    state.set(m.name, 'done')
    out.push(m)
  }
  for (const m of models) visit(m, [])
  return out
}

// ───────────────────────────── Postgres ─────────────────────────────

type PgTable = ReturnType<typeof pg.pgTable>
type PgBuilder = pg.PgColumnBuilderBase & { notNull(): PgBuilder; default(v: unknown): PgBuilder }

function pgColumn(def: FieldDef, col: string): PgBuilder {
  let b: PgBuilder
  switch (def.kind) {
    case 'string':
      b = pg.varchar(col, { length: def.length ?? 255 }) as unknown as PgBuilder
      break
    case 'text':
    case 'enum':
      b = pg.text(col) as unknown as PgBuilder
      break
    case 'integer':
      b = pg.integer(col) as unknown as PgBuilder
      break
    case 'decimal':
      b = pg.numeric(col, { precision: def.precision ?? 12, scale: def.scale ?? 2 }) as unknown as PgBuilder
      break
    case 'boolean':
      b = pg.boolean(col) as unknown as PgBuilder
      break
    case 'date':
      b = pg.date(col, { mode: 'string' }) as unknown as PgBuilder
      break
    case 'belongsTo':
      b = pg.uuid(col) as unknown as PgBuilder // FK added as a named table constraint
      break
  }
  if (def.required) b = b.notNull()
  if (def.default !== undefined) b = b.default(def.kind === 'decimal' ? String(def.default) : def.default)
  return b
}

export function compilePg(models: readonly ModelDefinition[], options: CompileOptions = {}): Record<string, PgTable> {
  const naming = options.naming ?? defaultNaming
  assertTargets(models)
  const tables: Record<string, PgTable> = {}
  const byModel = new Map<string, PgTable>()
  const targetId = (target: string): pg.AnyPgColumn => {
    const t = byModel.get(target) as unknown as { id?: pg.AnyPgColumn } | undefined
    if (!t?.id) throw new Error(`Unknown belongsTo target ${target}`)
    return t.id
  }

  // Targets before dependants, so foreign keys reference already-compiled tables.
  for (const m of topoSort(models)) {
    const cols: Record<string, pg.PgColumnBuilderBase> = { id: pg.uuid('id').primaryKey() }
    if (m.options.tenant) cols.tenant_id = pg.uuid('tenant_id').notNull()
    for (const [key, def] of Object.entries(m.fields)) {
      const col = columnName(key, def)
      cols[col] = pgColumn(def, col)
    }
    if (m.options.timestamps) {
      cols.created_at = pg.timestamp('created_at', { withTimezone: true }).notNull().defaultNow()
      cols.updated_at = pg.timestamp('updated_at', { withTimezone: true }).notNull().defaultNow()
    }
    if (m.options.softDeletes) cols.deleted_at = pg.timestamp('deleted_at', { withTimezone: true })

    const table = pg.pgTable(m.table, cols, (t) => {
      const c = t as unknown as Record<string, pg.AnyPgColumn>
      const at = (col: string): pg.AnyPgColumn => {
        const column = c[col]
        if (!column) throw new Error(`Internal: column ${m.table}.${col} missing`)
        return column
      }
      const extras: (pg.IndexBuilder | pg.CheckBuilder | pg.ForeignKeyBuilder)[] = []
      if (m.options.tenant) extras.push(pg.index(naming('tenantIndex', m.table, 'tenant_id')).on(at('tenant_id')))
      for (const [key, def] of Object.entries(m.fields)) {
        const col = columnName(key, def)
        if (def.unique) {
          const idx = pg.uniqueIndex(naming('unique', m.table, col))
          extras.push(m.options.tenant ? idx.on(at('tenant_id'), at(col)) : idx.on(at(col)))
        }
        if (def.index || def.kind === 'belongsTo') extras.push(pg.index(naming('index', m.table, col)).on(at(col)))
        if (def.kind === 'enum') extras.push(pg.check(naming('check', m.table, col), enumCheck(col, def.values ?? [])))
        if (def.kind === 'belongsTo') {
          extras.push(
            pg
              .foreignKey({ name: naming('fk', m.table, col), columns: [at(col)], foreignColumns: [targetId(def.target as string)] })
              .onDelete('restrict')
              .onUpdate('cascade'),
          )
        }
      }
      return extras
    })
    tables[m.table] = table
    byModel.set(m.name, table)
  }
  return tables
}

// ───────────────────────────── SQLite ─────────────────────────────

type LiteTable = ReturnType<typeof lite.sqliteTable>
type LiteBuilder = lite.SQLiteColumnBuilderBase & { notNull(): LiteBuilder; default(v: unknown): LiteBuilder }

function liteColumn(def: FieldDef, col: string): LiteBuilder {
  let b: LiteBuilder
  switch (def.kind) {
    case 'string':
    case 'text':
    case 'enum':
    case 'decimal': // TEXT on purpose: preserves exact decimal values
    case 'date': // ISO-8601 'YYYY-MM-DD'
    case 'belongsTo': // UUID as text; FK added as a named table constraint
      b = lite.text(col) as unknown as LiteBuilder
      break
    case 'integer':
      b = lite.integer(col) as unknown as LiteBuilder
      break
    case 'boolean':
      b = lite.integer(col, { mode: 'boolean' }) as unknown as LiteBuilder
      break
  }
  if (def.required) b = b.notNull()
  if (def.default !== undefined) b = b.default(def.kind === 'decimal' ? String(def.default) : def.default)
  return b
}

export function compileSqlite(models: readonly ModelDefinition[], options: CompileOptions = {}): Record<string, LiteTable> {
  const naming = options.naming ?? defaultNaming
  assertTargets(models)
  const tables: Record<string, LiteTable> = {}
  const byModel = new Map<string, LiteTable>()
  const targetId = (target: string): lite.AnySQLiteColumn => {
    const t = byModel.get(target) as unknown as { id?: lite.AnySQLiteColumn } | undefined
    if (!t?.id) throw new Error(`Unknown belongsTo target ${target}`)
    return t.id
  }

  for (const m of topoSort(models)) {
    const cols: Record<string, lite.SQLiteColumnBuilderBase> = { id: lite.text('id').primaryKey() }
    if (m.options.tenant) cols.tenant_id = lite.text('tenant_id').notNull()
    for (const [key, def] of Object.entries(m.fields)) {
      const col = columnName(key, def)
      cols[col] = liteColumn(def, col)
    }
    if (m.options.timestamps) {
      // No CURRENT_TIMESTAMP default: SQLite rejects non-constant defaults in ALTER TABLE ADD COLUMN.
      // The framework sets timestamps in application code instead.
      cols.created_at = lite.text('created_at').notNull()
      cols.updated_at = lite.text('updated_at').notNull()
    }
    if (m.options.softDeletes) cols.deleted_at = lite.text('deleted_at')

    const table = lite.sqliteTable(m.table, cols, (t) => {
      const c = t as unknown as Record<string, lite.AnySQLiteColumn>
      const at = (col: string): lite.AnySQLiteColumn => {
        const column = c[col]
        if (!column) throw new Error(`Internal: column ${m.table}.${col} missing`)
        return column
      }
      const extras: (lite.IndexBuilder | lite.CheckBuilder | lite.ForeignKeyBuilder)[] = []
      if (m.options.tenant) extras.push(lite.index(naming('tenantIndex', m.table, 'tenant_id')).on(at('tenant_id')))
      for (const [key, def] of Object.entries(m.fields)) {
        const col = columnName(key, def)
        if (def.unique) {
          const idx = lite.uniqueIndex(naming('unique', m.table, col))
          extras.push(m.options.tenant ? idx.on(at('tenant_id'), at(col)) : idx.on(at(col)))
        }
        if (def.index || def.kind === 'belongsTo') extras.push(lite.index(naming('index', m.table, col)).on(at(col)))
        if (def.kind === 'enum') extras.push(lite.check(naming('check', m.table, col), enumCheck(col, def.values ?? [])))
        if (def.kind === 'belongsTo') {
          extras.push(
            lite
              .foreignKey({ name: naming('fk', m.table, col), columns: [at(col)], foreignColumns: [targetId(def.target as string)] })
              .onDelete('restrict')
              .onUpdate('cascade'),
          )
        }
      }
      return extras
    })
    tables[m.table] = table
    byModel.set(m.name, table)
  }
  return tables
}
