/**
 * The text of the files `charts:sync` writes. Pure functions (metadata in, text out), so the
 * output is deterministic: LF line endings, sorted keys, no machine paths or timestamps.
 *
 * @module
 */
import { capabilitiesOf, DEFAULT_TENANT_COLUMN } from '../shared/capabilities.ts'
import { isExposedField, isInternalResource } from '../shared/exposure.ts'
import type { AppMetadata, FieldMetadata, ResourceMetadata } from '../shared/metadata.ts'
import { suggestCharts } from '../shared/suggest.ts'

/**
 * The lock file: suggestion ids per resource at the last sync, so the next sync can say "new".
 *
 * @example
 * const lock: ChartsLock = { version: 1, suggestions: { invoices: ['invoices.new'] } }
 */
export interface ChartsLock {
  readonly version: 1
  readonly suggestions: Readonly<Record<string, readonly string[]>>
}

/**
 * The chartable resources, sorted by route (internal tables never appear anywhere generated).
 *
 * @example
 * chartableResources(metadata).map((resource) => resource.route) // ['customers', 'employees', …]
 */
export function chartableResources(metadata: AppMetadata): ResourceMetadata[] {
  return metadata.resources.filter((resource) => !isInternalResource(resource)).sort((a, b) => a.route.localeCompare(b.route))
}

/**
 * The owned file's path, relative to the app root.
 *
 * @example
 * ownedPath('invoices') // 'resources/charts/invoices.charts.ts'
 */
export function ownedPath(route: string): string {
  return `resources/charts/${route}.charts.ts`
}

/**
 * Render `.strutvane/charts.gen.ts`.
 *
 * @example
 * renderRegistry(metadata, new Set(['invoices'])) // "// Generated by `charts:sync` …"
 */
export function renderRegistry(metadata: AppMetadata, ownedRoutes: ReadonlySet<string>, tenantColumn: string | false = DEFAULT_TENANT_COLUMN): string {
  const resources = chartableResources(metadata)
  const owned = resources.filter((resource) => ownedRoutes.has(resource.route))
  const lines = [
    '// Generated by `charts:sync` from .strutvane/resources.json. Do not edit: every migrate rewrites this file.',
    '// Your chart settings live in resources/charts/*.charts.ts, which charts:sync never overwrites.',
    "import type { AppMetadata, ResourceCharts } from '#strutvane/charts'",
    ...owned.map((resource) => `import ${importName(resource.route)} from '../${ownedPath(resource.route)}'`),
    '',
    "declare module '#strutvane/charts' {",
    '  /** Chart roles per resource: owned files are type-checked against these. */',
    '  interface ChartsRegistry {',
    ...resources.map((resource) => `    ${propertyKey(resource.route)}: ${registryEntry(metadata, resource, tenantColumn)}`),
    '  }',
    '}',
    '',
    '/** The resource metadata the charts are built from (internal tables removed). */',
    `export const metadata: AppMetadata = ${JSON.stringify({ version: 1, resources: resources.map(trimResource) }, null, 2)}`,
    '',
    '/** Every owned chart file, imported statically so the bundler and TypeScript see them. */',
    `export const ownedCharts: readonly ResourceCharts[] = [${owned.map((resource) => importName(resource.route)).join(', ')}]`,
    '',
  ]
  return lines.join('\n')
}

/** `{ numeric: 'total' | 'tax'; … }` for one resource; an empty role is `never`. */
function registryEntry(metadata: AppMetadata, resource: ResourceMetadata, tenantColumn: string | false): string {
  const capabilities = capabilitiesOf(metadata, resource, tenantColumn)
  const roles: readonly (readonly [string, readonly string[]])[] = [
    ['numeric', capabilities.numeric],
    ['date', capabilities.date],
    ['category', capabilities.category],
    ['relation', capabilities.relation.map((relation) => relation.field)],
    ['suggestion', suggestCharts(metadata, resource, tenantColumn).map((widget) => widget.id)],
  ]
  return `{ ${roles.map(([role, names]) => `${role}: ${union(names)}`).join('; ')} }`
}

function union(names: readonly string[]): string {
  return names.length === 0 ? 'never' : names.map((name) => `'${name}'`).join(' | ')
}

/**
 * Render a new owned file. Written once, for a new resource only; never touched again.
 *
 * @example
 * renderOwnedFile(invoices) // "// Chart settings for Invoices …"
 */
export function renderOwnedFile(resource: ResourceMetadata): string {
  return [
    `// Chart settings for ${resource.label.plural}. \`node strut charts:sync\` wrote this file once and never`,
    '// overwrites it: edit freely. Field names and suggestion ids are type-checked.',
    "import { auto, defineResourceCharts } from '#strutvane/charts'",
    '',
    `export default defineResourceCharts('${resource.route}', {`,
    `  // The suggested charts. New suggestions appear after each migrate; auto({ except: ['${resource.route}.…'] }) hides one.`,
    '  widgets: auto(),',
    '  // What the home dashboard shows from this resource (false hides it).',
    '  dashboard: auto(),',
    "  // What the aggregate API accepts. A list narrows it: { numeric: ['amount'], groupBy: ['status'] }.",
    '  aggregates: auto(),',
    '  // Sensitive data (salaries, health)? Never show a group smaller than k people:',
    '  // privacy: { minGroupSize: 5 },',
    '})',
    '',
  ].join('\n')
}

/**
 * Render the lock file.
 *
 * @example
 * renderLock(metadata) // '{\n  "version": 1, …'
 */
export function renderLock(metadata: AppMetadata, tenantColumn: string | false = DEFAULT_TENANT_COLUMN): string {
  const suggestions = Object.fromEntries(chartableResources(metadata).map((resource) => [resource.route, suggestCharts(metadata, resource, tenantColumn).map((widget) => widget.id)]))
  const lock: ChartsLock = { version: 1, suggestions }
  return `${JSON.stringify(lock, null, 2)}\n`
}

/**
 * Keep only the keys charts read. resources.json carries more (inputs, searchable, …) that the
 * browser bundle doesn't need, and the typed `metadata` export would reject as unknown keys.
 */
function trimResource(resource: ResourceMetadata): ResourceMetadata {
  const { table, model, route, label, primaryKey, titleField, timestamps, softDeletes, relations, sidebar } = resource
  return {
    table,
    model,
    route,
    label,
    primaryKey,
    titleField,
    timestamps,
    softDeletes,
    // Secret and hidden columns never reach the browser bundle, not even as names (F-03).
    fields: resource.fields.filter(isExposedField).map(trimField),
    relations,
    sidebar,
    ...(resource.internal === undefined ? {} : { internal: resource.internal }),
    ...(resource.global === undefined ? {} : { global: resource.global }),
  }
}

function trimField(field: FieldMetadata): FieldMetadata {
  const { name, label, kind, cast, nullable, hidden, filterOperators, precision, scale, options, references, secret, aggregatable, personal } = field
  return {
    name,
    label,
    kind,
    cast,
    nullable,
    hidden,
    filterOperators,
    ...(precision === undefined ? {} : { precision }),
    ...(scale === undefined ? {} : { scale }),
    ...(options === undefined ? {} : { options }),
    ...(references === undefined ? {} : { references }),
    ...(secret === undefined ? {} : { secret }),
    // The browser resolves the same capabilities as the server, so it needs the same flags.
    ...(aggregatable === undefined ? {} : { aggregatable }),
    ...(personal === undefined ? {} : { personal }),
  }
}

/** `invoices` → `invoicesCharts`; `order_lines` → `orderLinesCharts`. */
function importName(route: string): string {
  return `${route.replace(/[-_]([a-z0-9])/g, (_, letter: string) => letter.toUpperCase())}Charts`
}

/** Quote a property key only when it isn't a plain identifier. */
function propertyKey(route: string): string {
  return /^[a-z_$][a-z0-9_$]*$/i.test(route) ? route : `'${route}'`
}
