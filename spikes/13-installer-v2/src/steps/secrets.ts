/**
 * Step "secrets": fill every missing secret in `.env` (APP_KEY, AUTH_SECRET, DB_PASSWORD, ...).
 *
 * Rules (security review F-17):
 * - each secret is 32 random bytes from `crypto.randomBytes`, base64url;
 * - an existing value is kept (resuming never logs anyone out or breaks a database password),
 *   except the app's own keys (APP_KEY, AUTH_SECRET) when they are too short to be real:
 *   placeholders such as "changeme" are replaced;
 * - `.env` is made readable by its owner only (mode 0600) on macOS and Linux;
 * - `.env.example` is never touched: it must stay free of secrets.
 *
 * @module
 */
import { chmodSync } from 'node:fs'
import { join } from 'node:path'
import { parseEnv, setEnvValue } from '../env-file.ts'
import type { ProjectOptions } from '../options.ts'
import { secretKeys } from '../templates/env.ts'
import { readEnvFile, writeEnvFile } from './env-io.ts'
import type { Step } from './types.ts'

/** Keys the app itself owns: a short value there can only be a placeholder. */
const APP_KEYS: ReadonlySet<string> = new Set(['APP_KEY', 'AUTH_SECRET'])

/** 32 bytes as base64url are 43 characters; anything shorter was not generated by us. */
export const MINIMUM_SECRET_LENGTH = 43

/**
 * The secret keys that need a (new) value: empty ones, plus app keys that are too short.
 *
 * Used by the step, and by resume to re-check a `done` secrets step instead of trusting
 * setup.json (a forged or stale file must not leave the app with a placeholder key).
 *
 * @example
 * secretsNeedingValues(text, options) // ['APP_KEY'] when APP_KEY=changeme
 */
export function secretsNeedingValues(envText: string, options: ProjectOptions): string[] {
  const env = parseEnv(envText)
  return secretKeys(options).filter((key) => {
    const value = env.get(key) ?? ''
    if (value === '') return true
    return APP_KEYS.has(key) && value.length < MINIMUM_SECRET_LENGTH
  })
}

/** Owner-only permissions; Windows has no POSIX modes (the user profile ACL protects it there). */
function restrictToOwner(path: string): void {
  if (process.platform !== 'win32') chmodSync(path, 0o600)
}

/**
 * The secrets step.
 *
 * @example
 * await secretsStep.run(context) // { status: 'done', message: 'Secrets generated in .env (APP_KEY, ...)' }
 */
export const secretsStep: Step = {
  id: 'secrets',
  title: 'Generating secrets',
  needs: () => ['files'],
  applies: () => true,
  run: async (context) => {
    let text = readEnvFile(context.directory)
    const missing = secretsNeedingValues(text, context.options)
    for (const key of missing) text = setEnvValue(text, key, context.generateSecret())
    if (missing.length > 0) writeEnvFile(context.directory, '.env', text)
    restrictToOwner(join(context.directory, '.env'))
    if (missing.length === 0) return { status: 'done', message: 'Secrets already set in .env' }
    return { status: 'done', message: `Secrets generated in .env (${missing.join(', ')})` }
  },
}
