/**
 * Docker mode: the git-ignored `docker/compose.yaml` that runs EVERYTHING in containers, like
 * Laravel Sail (ADR-0006: Docker is local-only, never committed), plus the database's first-start
 * init script.
 *
 * Services:
 * - `app`: the official `node:24` image. The project folder is bind-mounted at `/app`;
 *   `node_modules` lives in a named volume (fast on Windows/macOS, and no native-module mix-up
 *   between the host OS and Linux). The container idles; `node strut <cmd>` on the host runs
 *   `docker compose exec app node strut <cmd>`, so `npm run dev` serves API + UI from the
 *   container on one port (HMR uses the same port). File watching polls, because change events
 *   do not cross Windows/macOS bind mounts reliably.
 * - `db`: MySQL 8.4 (default) or PostgreSQL 18; absent for SQLite (a file in the project).
 * - `mailpit`: catches every email the app sends; inbox at http://localhost:8025.
 *
 * Rules (security review F-19/F-20, user brief):
 * - every published port is bound to 127.0.0.1;
 * - secrets come only from `.env` (`env_file` for the app, `${VAR:?}` for the database); nothing is
 *   baked into an image, and no password is ever on a command line;
 * - health checks on every service with state, so `docker compose up -d --wait` returns only
 *   when the database really accepts connections (init scripts included);
 * - the app runs as `${STRUT_UID}:${STRUT_GID}` (the host user on Linux), never as root;
 * - PostgreSQL gets an owner role (migrations) and a plain app role (NOSUPERUSER, NOBYPASSRLS).
 *
 * @module
 */
import { sqlIdentifier, testDatabaseName } from '../names.ts'
import type { ProjectOptions } from '../options.ts'
import type { GeneratedFile } from './app-files.ts'

/** The pinned images: one line each (re-verify before a release). Mailpit: v1.33, 2026-11-07. */
export const IMAGES = Object.freeze({
  node: 'node:24',
  mysql: 'mysql:8.4',
  postgres: 'postgres:18-alpine',
  mailpit: 'axllent/mailpit:v1.33',
} as const)

/** The named volume that holds `node_modules` inside the app container. */
export const NODE_MODULES_VOLUME = 'node-modules'

/**
 * Every Docker file for these options, or an empty list without Docker.
 *
 * @example
 * dockerFiles({ ...options, docker: true }).map((f) => f.path)
 * // ['docker/compose.yaml', 'docker/initdb/create-test-database.sql']
 */
export function dockerFiles(options: ProjectOptions): GeneratedFile[] {
  if (!options.docker) return []
  const files: GeneratedFile[] = [{ path: 'docker/compose.yaml', content: renderCompose(options) }]
  if (options.database === 'mysql') files.push({ path: 'docker/initdb/create-test-database.sql', content: mysqlInit(options) })
  if (options.database === 'postgres') files.push({ path: 'docker/initdb/create-roles.sh', content: POSTGRES_INIT })
  return files
}

/**
 * The compose file for Docker mode.
 *
 * @example
 * renderCompose({ ...options, docker: true, database: 'mysql' }) // 'services:\n  app:\n    image: node:24 ...'
 */
export function renderCompose(options: ProjectOptions): string {
  const header = [
    `# Local development for ${options.name}: everything runs in containers (like Laravel Sail).`,
    '# Generated by create-strutvane and git-ignored (ADR-0006). Settings and passwords come from .env.',
    '# Start: node strut services:up   Stop: node strut services:down   Any command: node strut <cmd>',
    '',
  ].join('\n')
  const database = options.database === 'mysql' ? MYSQL : options.database === 'postgres' ? POSTGRES : ''
  const dependsOn = options.database === 'sqlite' ? '' : '      db:\n        condition: service_healthy\n'
  const volumes = options.database === 'sqlite' ? '' : '  db-data:\n'
  return `${header}services:
${app(dependsOn)}${database}${MAILPIT}
volumes:
  ${NODE_MODULES_VOLUME}:
${volumes}`
}

/** The app service: idles, so every `node strut` command (and `npm run dev`) runs through exec. */
function app(dependsOn: string): string {
  return `  app:
    image: ${IMAGES.node}
    working_dir: /app
    # Runs as you on Linux (no root-owned files); Docker Desktop maps ownership on Windows/macOS.
    user: "\${STRUT_UID:-1000}:\${STRUT_GID:-1000}"
    init: true # stops in a second instead of ten (PID 1 forwards signals)
    command: ["sleep", "infinity"]
    env_file: ../.env
    environment:
      STRUTVANE_IN_CONTAINER: "1" # strut.js runs commands here instead of forwarding again
      APP_HOST: 0.0.0.0 # listen on the container network; the host side is 127.0.0.1 only
      HOME: /tmp # any UID can write here (npm cache, tool config)
      npm_config_cache: /tmp/.npm
      npm_config_update_notifier: "false"
      CHOKIDAR_USEPOLLING: "1" # file events do not cross Windows/macOS bind mounts reliably
      STRUT_WATCH_POLLING: "1"
    ports:
      - "127.0.0.1:\${APP_PORT:?set APP_PORT in .env}:\${APP_PORT:?set APP_PORT in .env}"
    volumes:
      - ..:/app
      - ${NODE_MODULES_VOLUME}:/app/node_modules
${dependsOn.length > 0 ? `    depends_on:\n${dependsOn}` : ''}`
}

const MYSQL = `  db:
    image: ${IMAGES.mysql}
    environment:
      MYSQL_DATABASE: \${DB_DATABASE:?set DB_DATABASE in .env}
      MYSQL_USER: \${DB_USERNAME:?set DB_USERNAME in .env}
      MYSQL_PASSWORD: \${DB_PASSWORD:?set DB_PASSWORD in .env (npm run setup generates it)}
      MYSQL_ROOT_PASSWORD: \${DB_ROOT_PASSWORD:?set DB_ROOT_PASSWORD in .env (npm run setup generates it)}
    ports:
      - "127.0.0.1:\${FORWARD_DB_PORT:?set FORWARD_DB_PORT in .env}:3306"
    volumes:
      - db-data:/var/lib/mysql
      - ./initdb:/docker-entrypoint-initdb.d:ro
    healthcheck:
      # TCP on 127.0.0.1: only the final server (after init scripts) listens there. The password
      # comes from the container's environment (MYSQL_PWD), never from argv.
      test: ["CMD-SHELL", "MYSQL_PWD=\\"$$MYSQL_ROOT_PASSWORD\\" mysqladmin ping -h 127.0.0.1 -u root --silent"]
      interval: 2s
      timeout: 5s
      retries: 90
      start_period: 5s
`

const POSTGRES = `  db:
    image: ${IMAGES.postgres}
    environment:
      # The image's superuser ("postgres") is only used by the init script, never by the app.
      POSTGRES_PASSWORD: \${DB_ROOT_PASSWORD:?set DB_ROOT_PASSWORD in .env (npm run setup generates it)}
      STRUT_DB_NAME: \${DB_DATABASE:?set DB_DATABASE in .env}
      STRUT_DB_TEST_NAME: \${DB_TEST_DATABASE:?set DB_TEST_DATABASE in .env}
      STRUT_DB_OWNER: \${DB_MIGRATION_USERNAME:?set DB_MIGRATION_USERNAME in .env}
      STRUT_DB_OWNER_PASSWORD: \${DB_MIGRATION_PASSWORD:?set DB_MIGRATION_PASSWORD in .env (npm run setup generates it)}
      STRUT_DB_APP: \${DB_USERNAME:?set DB_USERNAME in .env}
      STRUT_DB_APP_PASSWORD: \${DB_PASSWORD:?set DB_PASSWORD in .env (npm run setup generates it)}
    ports:
      - "127.0.0.1:\${FORWARD_DB_PORT:?set FORWARD_DB_PORT in .env}:5432"
    volumes:
      - db-data:/var/lib/postgresql
      - ./initdb:/docker-entrypoint-initdb.d:ro
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -h 127.0.0.1 -U postgres"]
      interval: 2s
      timeout: 5s
      retries: 90
      start_period: 5s
`

const MAILPIT = `  mailpit:
    image: ${IMAGES.mailpit}
    # SMTP (1025) stays on the container network; only the inbox is published, to 127.0.0.1.
    ports:
      - "127.0.0.1:\${FORWARD_MAILPIT_PORT:-8025}:8025"
    healthcheck:
      test: ["CMD", "/mailpit", "readyz"]
      interval: 2s
      timeout: 5s
      retries: 30
`

/** MySQL: the image creates `DB_DATABASE` and `DB_USERNAME`; this adds the test database. */
function mysqlInit(options: ProjectOptions): string {
  const user = sqlIdentifier(options.name)
  const test = testDatabaseName(options.name)
  // The names are validated identifiers (letters, digits, _), so static SQL is safe here.
  return [
    '-- Test database for npm test, created once on the first start of the container.',
    `CREATE DATABASE IF NOT EXISTS ${test};`,
    `GRANT ALL PRIVILEGES ON ${test}.* TO '${user}'@'%';`,
    '',
  ].join('\n')
}

/**
 * PostgreSQL first-start script: an owner role for migrations and a plain app role, in the dev and
 * the test database. psql variables (`:"name"`, `:'value'`) quote identifiers and passwords, so
 * values from `.env` can never break out of the SQL.
 */
const POSTGRES_INIT = `#!/bin/sh
# Creates the owner and app roles and both databases on the first start (security review F-20).
set -eu

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname postgres \\
  -v owner="$STRUT_DB_OWNER" -v owner_password="$STRUT_DB_OWNER_PASSWORD" \\
  -v app="$STRUT_DB_APP" -v app_password="$STRUT_DB_APP_PASSWORD" \\
  -v db="$STRUT_DB_NAME" -v test_db="$STRUT_DB_TEST_NAME" <<'EOSQL'
CREATE ROLE :"owner" LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE PASSWORD :'owner_password';
CREATE ROLE :"app" LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE PASSWORD :'app_password';
CREATE DATABASE :"db" OWNER :"owner";
CREATE DATABASE :"test_db" OWNER :"owner";
EOSQL

for database in "$STRUT_DB_NAME" "$STRUT_DB_TEST_NAME"; do
  psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$database" \\
    -v owner="$STRUT_DB_OWNER" -v app="$STRUT_DB_APP" <<'EOSQL'
ALTER SCHEMA public OWNER TO :"owner";
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO :"app";
ALTER DEFAULT PRIVILEGES FOR ROLE :"owner" IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO :"app";
ALTER DEFAULT PRIVILEGES FOR ROLE :"owner" IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO :"app";
EOSQL
done
`
