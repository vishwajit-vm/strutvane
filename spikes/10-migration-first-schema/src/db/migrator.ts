/**
 * `sv migrate` and `sv migrate:rollback`, Laravel-style: a `strutvane_migrations` table remembers
 * which migrations ran and in which batch, and a rollback undoes the last batch in reverse order.
 *
 * The SQL comes from the *same* recorded operations the types were generated from (see
 * `replay.ts`), so what runs and what TypeScript believes can't drift apart.
 */
import { SqlParams } from '../sql/dialect.ts'
import { compileOperations } from '../sql/ddl.ts'
import type { Replay, ReplayedMigration } from '../schema/replay.ts'
import type { Database } from './database.ts'

/** Where ran migrations are recorded. Laravel calls it `migrations`; prefixed here to avoid clashes with app tables. */
export const MIGRATIONS_TABLE = 'strutvane_migrations'

/**
 * A row of the migrations table.
 *
 * @example
 * const ran: RanMigration = { name: '2026_01_02_000000_create_posts_table', batch: 1 }
 */
export interface RanMigration {
  readonly name: string
  readonly batch: number
}

/**
 * Run every pending migration, each in its own transaction, as one new batch.
 *
 * Fail closed: if a migration fails, its transaction rolls back (no half-created table, no row in
 * the migrations table), the error is re-thrown, and later migrations don't run.
 *
 * @example
 * const { ran, batch } = await migrate(db, replay) // ran: ['2026_01_01_…_create_users_table', …]
 */
export async function migrate(db: Database, replay: Replay): Promise<{ ran: string[]; batch: number }> {
  await ensureMigrationsTable(db)
  const done = new Set((await ranMigrations(db)).map((row) => row.name))
  assertNoUnknownMigrations(done, replay)
  const pending = replay.migrations.filter((step) => !done.has(step.name))
  const batch = (await lastBatch(db)) + 1
  const ran: string[] = []
  for (const step of pending) {
    await db.transaction(async (tx) => {
      for (const sql of upSql(step, db.dialect)) await tx.execute(sql)
      const params = new SqlParams(db.dialect)
      await tx.query(`INSERT INTO "${MIGRATIONS_TABLE}" ("name", "batch") VALUES (${params.add(step.name)}, ${params.add(batch)})`, params.values)
    })
    ran.push(step.name)
  }
  return { ran, batch: ran.length === 0 ? batch - 1 : batch }
}

/**
 * Undo migrations by running their recorded `down()` operations, newest first.
 * By default the last batch is undone, like `migrate:rollback`; `{ all: true }` is `migrate:reset`.
 *
 * @example
 * await rollback(db, replay) // undoes the last batch
 * await rollback(db, replay, { all: true }) // back to an empty database
 */
export async function rollback(db: Database, replay: Replay, options: { readonly all?: boolean } = {}): Promise<string[]> {
  await ensureMigrationsTable(db)
  const ran = await ranMigrations(db)
  const batch = await lastBatch(db)
  const targets = ran.filter((row) => options.all === true || row.batch === batch).reverse()
  const byName = new Map(replay.migrations.map((step) => [step.name, step]))
  const undone: string[] = []
  for (const row of targets) {
    const step = byName.get(row.name)
    if (step === undefined) throw missingFileError(row.name)
    await db.transaction(async (tx) => {
      for (const sql of downSql(step, db.dialect)) await tx.execute(sql)
      const params = new SqlParams(db.dialect)
      await tx.query(`DELETE FROM "${MIGRATIONS_TABLE}" WHERE "name" = ${params.add(row.name)}`, params.values)
    })
    undone.push(row.name)
  }
  return undone
}

/**
 * The SQL `up()` runs, compiled from the schema as it was right before the migration.
 *
 * @example
 * upSql(replay.migrations[0], 'postgres') // ['CREATE TABLE "users" (…)', …]
 */
export function upSql(step: ReplayedMigration, dialect: Database['dialect'] | 'mysql' | 'mariadb'): string[] {
  return compileOperations(step.before, step.up, dialect)
}

/**
 * The SQL `down()` runs, compiled from the schema as `up()` left it.
 *
 * @example
 * downSql(replay.migrations[0], 'sqlite') // ['DROP TABLE IF EXISTS "users"']
 */
export function downSql(step: ReplayedMigration, dialect: Database['dialect'] | 'mysql' | 'mariadb'): string[] {
  return compileOperations(step.after, step.down, dialect)
}

/**
 * Which migrations have run, oldest first.
 *
 * @example
 * await ranMigrations(db) // [{ name: '2026_01_01_…', batch: 1 }, …]
 */
export async function ranMigrations(db: Database): Promise<RanMigration[]> {
  const rows = await db.query(`SELECT "name", "batch" FROM "${MIGRATIONS_TABLE}" ORDER BY "id"`)
  return rows.map((row) => ({ name: String(row['name']), batch: Number(row['batch']) }))
}

async function ensureMigrationsTable(db: Database): Promise<void> {
  const id = db.dialect === 'sqlite' ? 'INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL' : 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
  await db.execute(`CREATE TABLE IF NOT EXISTS "${MIGRATIONS_TABLE}" ("id" ${id}, "name" VARCHAR(255) NOT NULL UNIQUE, "batch" INTEGER NOT NULL)`)
}

async function lastBatch(db: Database): Promise<number> {
  const rows = await db.query(`SELECT MAX("batch") AS "batch" FROM "${MIGRATIONS_TABLE}"`)
  return Number(rows[0]?.['batch'] ?? 0)
}

/**
 * A migration that ran but whose file is gone would make the replayed schema (and the types)
 * disagree with the database. Refuse rather than generate wrong types.
 */
function assertNoUnknownMigrations(done: ReadonlySet<string>, replay: Replay): void {
  const known = new Set(replay.migrations.map((step) => step.name))
  const unknown = [...done].find((name) => !known.has(name))
  if (unknown !== undefined) throw missingFileError(unknown)
}

function missingFileError(name: string): Error {
  return new Error(
    `The database says "${name}" ran, but there is no such migration file. ` +
      'Restore the file (from version control) so Strutvane knows what the database looks like, or remove its row from strutvane_migrations if you are sure it never mattered.',
  )
}
