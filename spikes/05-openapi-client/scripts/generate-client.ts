/**
 * Generate `openapi.json` and the client TYPES (`src/client.gen/schema.d.ts`) from the app's model
 * definitions. Only types are generated; the runtime (`openapi-fetch`) is a normal npm dependency,
 * so no generated runtime code has to pass (or be excluded from) the strict tsconfig.
 *
 *   node scripts/generate-client.ts           # write openapi.json + src/client.gen/schema.d.ts
 *   node scripts/generate-client.ts --check   # exit 1 if the committed files are out of date (CI)
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'
import { createApp } from '../src/app.ts'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const SPEC_PATH: string = join(ROOT, 'openapi.json')
export const TYPES_PATH: string = join(ROOT, 'src', 'client.gen', 'schema.d.ts')

const HEADER = `/**
 * GENERATED by scripts/generate-client.ts from the Zod models (via openapi.json). Do not edit.
 * Regenerate: node scripts/generate-client.ts
 */
`

/** Produce the spec JSON text and the client types text. Pure: writes nothing. */
export async function render(): Promise<{ spec: string; types: string }> {
  const response = await createApp().request('/openapi.json')
  if (response.status !== 200) throw new Error(`/openapi.json returned ${response.status}`)
  const document = (await response.json()) as Record<string, unknown>
  const spec = `${JSON.stringify(document, null, 2)}\n`
  // `exactOptionalPropertyTypes`-friendly output; `alphabetize` gives a stable order independent of
  // route registration order.
  const ast = await openapiTS(document as unknown as Parameters<typeof openapiTS>[0], { alphabetize: true })
  return { spec, types: `${HEADER}${astToString(ast)}` }
}

async function main(): Promise<void> {
  const { spec, types } = await render()
  if (process.argv.includes('--check')) {
    const stale = [
      [SPEC_PATH, spec],
      [TYPES_PATH, types],
    ].filter(([path, content]) => !existsSync(path as string) || readFileSync(path as string, 'utf8') !== content)
    if (stale.length > 0) {
      process.stderr.write(`Out of date: ${stale.map(([p]) => p).join(', ')}\nRun: node scripts/generate-client.ts\n`)
      process.exitCode = 1
    } else process.stdout.write('openapi.json and client types are up to date.\n')
    return
  }
  mkdirSync(dirname(TYPES_PATH), { recursive: true })
  writeFileSync(SPEC_PATH, spec)
  writeFileSync(TYPES_PATH, types)
  process.stdout.write('Generated openapi.json and src/client.gen/schema.d.ts\n')
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main()
