#!/usr/bin/env node
/**
 * Local end-to-end journey for the whole ecosystem, against the local package checkouts.
 *
 *   node scripts/e2e-local.mjs [--skip-build] [--skip-tenancy]
 *   node --test scripts/e2e-local.test.mjs     (unit tests for the helpers)
 *
 * The generated apps stay in integration-local/ (git-ignored) for inspection.
 *
 * In the git-ignored `integration-local/` folder it:
 *  1. builds every package (contracts → … → create-strutvane);
 *  2. generates an app with the local create-strutvane (full preset, SQLite, email auth);
 *  3. installs it with pnpm `overrides` pointing every @strutvane package at the checkouts
 *     (`file:`, so packages land in node_modules like a real install);
 *  4. walks the journey: about/doctor/env:check → make:model → registry:build → migrate →
 *     dev + start servers → HTTP assertions (health, auth, CRUD, 422 problems, filters, sort,
 *     cursors, OpenAPI, manifest, permissions, request logs, log viewer) → production checks →
 *     boot refusal without a PermissionProvider → `sv build` (Vite against @strutvane/ui);
 *  5. repeats the tenancy-relevant steps on PostgreSQL 18 in a throwaway `docker run --rm`
 *     container, verifying tenant scoping over HTTP and RLS with a non-owner runtime role.
 *
 * Exits non-zero on the first failure. Nothing is published, pushed or committed; the
 * Postgres container is always removed. Test passwords are generated per run and never printed.
 */
