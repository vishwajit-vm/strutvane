// ─── Pure helpers (unit-tested in e2e-local.test.mjs) ────────────────────────────────────────

/** Parse the script's flags. Unknown flags are an error (typos must not silently skip steps). */
export function parseArgs(argv) {
  const known = { '--skip-build': 'skipBuild', '--skip-tenancy': 'skipTenancy' }
  const out = { skipBuild: false, skipTenancy: false }
  for (const arg of argv) {
    const key = known[arg]
    if (!key) throw new Error(`Unknown flag ${arg} (known: ${Object.keys(known).join(', ')})`)
    out[key] = true
  }
  return out
}

/**
 * The app's pnpm-workspace.yaml: every @strutvane package from the checkouts via `file:`
 * (`link:` would resolve outside node_modules, and the CLI refuses contributions from there).
 */
export function workspaceYaml(appDir, packagesDir, packages = LOCAL_PACKAGES) {
  const rel = (to) => relativePosix(appDir, to)
  const lines = [
    '# Generated by scripts/e2e-local.mjs (git-ignored). Local checkouts as real installs.',
    'overrides:',
    ...Object.entries(packages).map(
      ([name, path]) => `  ${JSON.stringify(name)}: file:${rel(join(packagesDir, path))}`,
    ),
    'allowBuilds:',
    '  esbuild: true',
    '',
  ]
  return lines.join('\n')
}

/** POSIX relative path from `from` to `to` (both absolute). */
export function relativePosix(from, to) {
  const a = resolve(from).split(/[\\/]+/)
  const b = resolve(to).split(/[\\/]+/)
  let i = 0
  while (i < a.length && i < b.length && a[i].toLowerCase() === b[i].toLowerCase()) i++
  return [...Array(a.length - i).fill('..'), ...b.slice(i)].join('/') || '.'
}

/** Parse a dotenv file's text (KEY=VALUE lines; comments and blanks ignored). */
export function parseEnv(text) {
  const out = {}
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim()
    if (!line || line.startsWith('#')) continue
    const eq = line.indexOf('=')
    if (eq <= 0) continue
    out[line.slice(0, eq).trim()] = line.slice(eq + 1).trim()
  }
  return out
}

/** The `name=value` pairs of every Set-Cookie header (attributes dropped). */
export function cookiesFrom(headers) {
  const list = typeof headers.getSetCookie === 'function' ? headers.getSetCookie() : []
  return list.map((c) => c.split(';')[0].trim()).filter((c) => c.includes('='))
}

/** Merge new cookies into a jar (Map name → `name=value`); expired (empty) values are removed. */
export function updateJar(jar, cookies) {
  for (const c of cookies) {
    const name = c.slice(0, c.indexOf('='))
    if (c.slice(name.length + 1) === '') jar.delete(name)
    else jar.set(name, c)
  }
  return jar
}

/** Encode list-query params (`filter[status][eq]=…`) the way the API expects. */
export function listQuery(params) {
  return Object.entries(params)
    .map(([k, v]) => `${encodeURIComponent(k)}=${encodeURIComponent(String(v))}`)
    .join('&')
}

/** A random secret for test-only passwords (never printed). */
export function secret(bytes = 24) {
  return randomBytes(bytes).toString('base64url')
}

// ─── Process helpers ─────────────────────────────────────────────────────────────────────────

const IS_WIN = process.platform === 'win32'
const baseEnv = () => ({ ...process.env, COREPACK_ENABLE_DOWNLOAD_PROMPT: '0', NO_COLOR: '1' })

function log(message) {
  process.stdout.write(`${message}\n`)
}

/** Run a command; throws with its output on a non-zero exit. Args must be shell-safe for pnpm. */
function run(cmd, args, options = {}) {
  // corepack is a .cmd shim on Windows, which Node only spawns through a shell; its args here are
  // fixed, shell-safe words.
  const useShell = IS_WIN && cmd === 'corepack'
  const r = spawnSync(cmd, args, {
    cwd: options.cwd ?? HUB,
    env: { ...baseEnv(), ...options.env },
    encoding: 'utf8',
    shell: useShell,
    maxBuffer: 64 * 1024 * 1024,
  })
  const output = `${r.stdout ?? ''}${r.stderr ?? ''}`
  if (options.allowFailure) return { code: r.status ?? 1, output }
  if (r.status !== 0) {
    throw new Error(`\`${cmd} ${args.join(' ')}\` failed (exit ${r.status}):\n${output.slice(-4000)}`)
  }
  return { code: 0, output }
}

/** `pnpm sv …` without the pnpm layer: node + the project's `strutvane` launcher. */
function sv(app, args, options = {}) {
  return run(process.execPath, [join(app, 'node_modules/strutvane/dist/bin.mjs'), ...args], {
    ...options,
    cwd: app,
  })
}

function freePort() {
  return new Promise((ok, fail) => {
    const s = createServer()
    s.once('error', fail)
    s.listen(0, '127.0.0.1', () => {
      const { port } = s.address()
      s.close(() => ok(port))
    })
  })
}

/** Kill a process and its children (dev spawns a watched child). */
function killTree(child) {
  if (child.exitCode !== null) return
  if (IS_WIN) spawnSync('taskkill', ['/pid', String(child.pid), '/T', '/F'], { stdio: 'ignore' })
  else child.kill('SIGTERM')
}

/** Start `sv <command> --port` and wait until /health answers. */
async function startServer(app, command, env = {}) {
  const port = await freePort()
  const base = `http://127.0.0.1:${port}`
  // The app's public origin (APP_URL → config/app.ts publicUrl) must be where the "browser" really
  // is: request URLs take that origin, and auth refuses sign-in from any other Origin.
  const child = spawn(
    process.execPath,
    [join(app, 'node_modules/strutvane/dist/bin.mjs'), command, '--port', String(port)],
    { cwd: app, env: { ...baseEnv(), APP_URL: base, ...env }, stdio: ['ignore', 'pipe', 'pipe'] },
  )
  let output = ''
  child.stdout.on('data', (d) => (output += d))
  child.stderr.on('data', (d) => (output += d))
  const deadline = Date.now() + 30_000
  while (Date.now() < deadline) {
    if (child.exitCode !== null) throw new Error(`sv ${command} exited early:\n${output}`)
    try {
      if ((await fetch(`${base}/health`)).ok) return { base, child, output: () => output }
    } catch {
      // not listening yet
    }
    await new Promise((r) => setTimeout(r, 250))
  }
  killTree(child)
  throw new Error(`sv ${command} did not become healthy:\n${output}`)
}

async function stopServer(server) {
  killTree(server.child)
  await new Promise((r) => (server.child.exitCode !== null ? r() : server.child.once('exit', r)))
}

// ─── Assertions ──────────────────────────────────────────────────────────────────────────────

const results = []

async function step(name, fn) {
  const started = Date.now()
  try {
    await fn()
    results.push({ name, ok: true })
    log(`  ✔ ${name} (${Date.now() - started} ms)`)
  } catch (error) {
    results.push({ name, ok: false })
    log(`  ✖ ${name}`)
    throw error
  }
}

function assert(condition, message) {
  if (!condition) throw new Error(`Assertion failed: ${message}`)
}

/** A tiny HTTP client with a cookie jar. */
function client(base) {
  const jar = new Map()
  const call = async (method, path, body, headers = {}) => {
    const h = { origin: base, ...headers }
    if (jar.size > 0) h.cookie = [...jar.values()].join('; ')
    if (body !== undefined) h['content-type'] = 'application/json'
    const res = await fetch(`${base}${path}`, {
      method,
      headers: h,
      ...(body !== undefined ? { body: JSON.stringify(body) } : {}),
    })
    updateJar(jar, cookiesFrom(res.headers))
    const text = await res.text()
    let json
    try {
      json = text ? JSON.parse(text) : undefined
    } catch {
      json = undefined
    }
    return { status: res.status, headers: res.headers, json, text }
  }
  return { call, jar }
}

// ─── Journey ─────────────────────────────────────────────────────────────────────────────────

function buildPackages() {
  for (const pkg of BUILD_ORDER) {
    const dir = join(PACKAGES, pkg)
    run(PNPM[0], [PNPM[1], 'run', 'build'], { cwd: dir })
  }
}

function generateApp(name, flags) {
  const app = join(WORK, name)
  // Windows can hold a just-closed SQLite or log file for a moment; retry for up to ~10 s.
  rmSync(app, { recursive: true, force: true, maxRetries: 20, retryDelay: 500 })
  mkdirSync(WORK, { recursive: true })
  run(process.execPath, [join(PACKAGES, 'create-strutvane/dist/cli.mjs'), name, ...flags], {
    cwd: WORK,
  })
  writeFileSync(join(app, 'pnpm-workspace.yaml'), workspaceYaml(app, PACKAGES))
  run(PNPM[0], [PNPM[1], 'install'], { cwd: app })
  return app
}

async function sqliteJourney() {
  log('\n▶ SQLite journey (full preset, email auth)')
  let app
  await step('generate + install the app with the local create-strutvane', () => {
    app = generateApp('app', [
      '--preset', 'full', '--db', 'sqlite', '--auth', 'email', '--no-tenancy',
      '--no-docker', '--pm', 'pnpm', '--no-git', '--yes',
    ])
  })
  const env = parseEnv(readFileSync(join(app, '.env'), 'utf8'))

  await step('sv about / doctor / env:check', () => {
    assert(sv(app, ['about']).output.includes('@strutvane/framework'), 'about lists packages')
    sv(app, ['doctor'])
    sv(app, ['env:check'])
  })
  await step('sv make:model Invoice … and a filterable Payment model', () => {
    sv(app, ['make:model', 'Invoice', 'number:string:unique', 'amount:decimal(12,2)',
      'status:enum(draft,sent,paid):default(draft)'])
    sv(app, ['make:model', 'Payment', 'reference:string:filterable:sortable',
      'amount:decimal(12,2):sortable', 'method:enum(card,bank):filterable'])
    assert(existsSync(join(app, 'app/policies/invoice.policy.ts')), 'policy generated')
  })
  await step('sv registry:build', () => sv(app, ['registry:build']))
  await step('sv migrate (+ idempotent rerun, migrate:status)', () => {
    assert(/Applied/.test(sv(app, ['migrate']).output), 'first migrate applies')
    assert(/Nothing to migrate/.test(sv(app, ['migrate']).output), 'second migrate is a no-op')
    assert(!/pending/.test(sv(app, ['migrate:status']).output), 'nothing pending')
  })
  await step('sv dev serves and stops', async () => {
    const dev = await startServer(app, 'dev')
    await stopServer(dev)
  })

  const server = await startServer(app, 'start')
  try {
    const admin = client(server.base)
    const anon = client(server.base)
    const api = '/api/v1'
    await step('health, custom route, deny-by-default for anonymous callers', async () => {
      assert((await anon.call('GET', '/health')).json?.status === 'ok', '/health')
      assert((await anon.call('GET', `${api}/hello`)).json?.message?.startsWith('Hello'), '/hello')
      const r = await anon.call('GET', `${api}/invoices`)
      assert(r.status === 401 && r.headers.get('content-type').includes('problem+json'), 'anon 401')
    })
    await step('auth: seed admin signs in, /me, wrong password 401, foreign origin 403', async () => {
      const bad = await anon.call('POST', `${api}/auth/sign-in`, {
        email: env.SEED_ADMIN_EMAIL, password: `${env.SEED_ADMIN_PASSWORD}x`,
      })
      assert(bad.status === 401, 'wrong password rejected')
      const crossSite = await anon.call(
        'POST',
        `${api}/auth/sign-in`,
        { email: env.SEED_ADMIN_EMAIL, password: env.SEED_ADMIN_PASSWORD },
        { origin: 'https://attacker.example' },
      )
      assert(crossSite.status === 403, 'sign-in from a foreign origin is refused')
      const ok = await admin.call('POST', `${api}/auth/sign-in`, {
        email: env.SEED_ADMIN_EMAIL, password: env.SEED_ADMIN_PASSWORD,
      })
      assert(ok.status === 200 && admin.jar.size > 0, 'signed in with a session cookie')
      assert((await admin.call('GET', `${api}/auth/me`)).json?.actor?.roles?.includes('admin'), 'admin role')
    })
    await step('CRUD on /api/v1/invoices with 422 problem+json issues', async () => {
      const c = await admin.call('POST', `${api}/invoices`, { number: 'INV-1', amount: '100.50' })
      assert(c.status === 201 && c.json.status === 'draft', 'create applies the default')
      const bad = await admin.call('POST', `${api}/invoices`, { number: 'INV-2', amount: 'abc', status: 'void' })
      assert(bad.status === 422 && bad.headers.get('content-type').includes('problem+json'), '422 problem')
      const paths = bad.json.issues.map((i) => i.path.join('.'))
      assert(paths.includes('amount') && paths.includes('status'), 'issues name the fields')
      const dup = await admin.call('POST', `${api}/invoices`, { number: 'INV-1', amount: '1.00' })
      assert(dup.status === 422 && dup.json.issues[0].code === 'unique', 'unique violation is an issue')
      const id = c.json.id
      assert((await admin.call('GET', `${api}/invoices/${id}`)).json.number === 'INV-1', 'show')
      assert((await admin.call('PATCH', `${api}/invoices/${id}`, { status: 'paid' })).json.status === 'paid', 'update')
      assert((await admin.call('DELETE', `${api}/invoices/${id}`)).status === 204, 'delete')
      assert((await admin.call('GET', `${api}/invoices/${id}`)).status === 404, 'gone')
    })
    await step('list filters, sort and cursor pagination', async () => {
      const rows = [['P-1', '30.00', 'card'], ['P-2', '10.00', 'bank'], ['P-3', '20.00', 'card'], ['P-4', '40.00', 'card']]
      for (const [reference, amount, method] of rows) {
        assert((await admin.call('POST', `${api}/payments`, { reference, amount, method })).status === 201, 'seed')
      }
      const q = listQuery({ 'filter[method][eq]': 'card', sort: '-amount', 'page[size]': 2 })
      const p1 = await admin.call('GET', `${api}/payments?${q}`)
      assert(p1.status === 200, `list ok (${p1.text.slice(0, 200)})`)
      assert(p1.json.data.map((r) => r.reference).join() === 'P-4,P-1', 'filtered + sorted page 1')
      const cursor = p1.json.meta.page.nextCursor
      assert(cursor, 'next cursor')
      const p2 = await admin.call('GET', `${api}/payments?${q}&${listQuery({ 'page[cursor]': cursor })}`)
      assert(p2.json.data.map((r) => r.reference).join() === 'P-3', 'page 2 via cursor')
      const unknown = await admin.call('GET', `${api}/invoices?${listQuery({ 'filter[status][eq]': 'x' })}`)
      assert(unknown.status === 422, 'non-filterable fields are refused')
    })
    await step('/openapi.json and /.well-known/strutvane.json', async () => {
      const doc = (await anon.call('GET', '/openapi.json')).json
      assert(doc.openapi.startsWith('3.1') && doc.paths[`${api}/invoices`], 'OpenAPI has invoices')
      const m = (await admin.call('GET', '/.well-known/strutvane.json')).json
      assert(m.resources.some((r) => r.name === 'Invoice'), 'manifest has Invoice')
    })
    await step('registration is off by default; with it on, a fresh sign-up has no role (deny-by-default)', async () => {
      const blocked = await client(server.base).call('POST', `${api}/auth/sign-up`, {
        email: 'member@app.test', password: secret(), name: 'Member',
      })
      assert(blocked.status === 403, 'sign-up refused while AUTH_ALLOW_REGISTRATION=false')
      const open = await startServer(app, 'start', { AUTH_ALLOW_REGISTRATION: 'true' })
      try {
        const user = client(open.base)
        const up = await user.call('POST', `${api}/auth/sign-up`, {
          email: 'member@app.test', password: secret(), name: 'Member',
        })
        assert(up.status === 201 && up.json.actor.roles.length === 0, 'signed up without roles')
        assert((await user.call('GET', `${api}/invoices`)).status === 403, 'list forbidden')
        assert((await user.call('POST', `${api}/invoices`, { number: 'X', amount: '1.00' })).status === 403, 'create forbidden')
      } finally {
        await stopServer(open)
      }
    })
    await step('request logs written by @strutvane/logs; viewer reachable locally', async () => {
      assert((await anon.call('GET', '/_strutvane/logs')).status === 200, 'viewer 200 in local')
      const dir = join(app, env.LOGS_PATH ?? 'storage/logs')
      const { readdirSync } = await import('node:fs')
      const files = readdirSync(dir).filter((f) => f.endsWith('.ndjson'))
      assert(files.length > 0, 'a log file exists')
      const text = files.map((f) => readFileSync(join(dir, f), 'utf8')).join('')
      assert(text.includes(`"route":"${api}/invoices"`), 'request lines logged')
      assert(!text.includes(env.SEED_ADMIN_PASSWORD) && !text.includes('sv_session='), 'no secrets in logs')
    })
  } finally {
    await stopServer(server)
  }

  await step('APP_ENV=production: viewer is a 404 without a token; API still guarded', async () => {
    const prod = await startServer(app, 'start', {
      APP_ENV: 'production',
      APP_DEBUG: 'false',
      // Production refuses non-https CORS origins.
      CORS_ORIGINS: 'https://app.example',
    })
    try {
      const c = client(prod.base)
      assert((await c.call('GET', '/_strutvane/logs')).status === 404, 'viewer hidden')
      assert((await c.call('GET', '/api/v1/invoices')).status === 401, 'API guarded')
    } finally {
      await stopServer(prod)
    }
  })
  await step('refuses to boot outside local without a PermissionProvider', () => {
    const file = join(app, 'strutvane.config.ts')
    const original = readFileSync(file, 'utf8')
    try {
      writeFileSync(
        file,
        original
          .replace(/^import authProvider .*\r?\n/m, '')
          .replace(/authProvider,\s*/, ''),
      )
      const r = sv(app, ['start', '--port', '0'], {
        // APP_DEBUG=true is itself refused outside local, so turn it off to reach the provider check.
        env: { APP_ENV: 'staging', APP_DEBUG: 'false' },
        allowFailure: true,
      })
      assert(r.code !== 0 && r.output.includes('No PermissionProvider'), 'boot refused')
    } finally {
      writeFileSync(file, original)
    }
  })
  await step('sv build: the app loads and Vite builds web/ against @strutvane/ui', () => {
    assert(/Web UI built/.test(sv(app, ['build']).output), 'vite build ran')
    assert(existsSync(join(app, 'dist/web/index.html')), 'dist/web/index.html')
  })
  return app
}

async function tenancyJourney() {
  log('\n▶ Tenancy journey (PostgreSQL 18 in a throwaway container, shared tenancy + RLS)')
  const docker = spawnSync('docker', ['version', '--format', '{{.Server.Version}}'], { encoding: 'utf8' })
  if (docker.status !== 0) throw new Error('Docker is not available (use --skip-tenancy to skip this leg)')
  const port = await freePort()
  const pgPassword = secret()
  const runtimePassword = secret()
  const container = `sv-e2e-pg-${process.pid}`
  run('docker', ['run', '--rm', '-d', '--name', container, '-e', `POSTGRES_PASSWORD=${pgPassword}`,
    '-e', 'POSTGRES_DB=app', '-p', `127.0.0.1:${port}:5432`, PG_IMAGE])
  const psql = (sql, user = 'postgres') =>
    run('docker', ['exec', '-e', `PGPASSWORD=${user === 'postgres' ? pgPassword : runtimePassword}`,
      container, 'psql', '-h', '127.0.0.1', '-U', user, '-d', 'app', '-tAc', sql]).output.trim()
  try {
    for (let i = 0; ; i++) {
      if (run('docker', ['exec', container, 'pg_isready', '-h', '127.0.0.1', '-U', 'postgres'], { allowFailure: true }).code === 0) break
      if (i > 60) throw new Error('Postgres did not start')
      await new Promise((r) => setTimeout(r, 500))
    }
    let app
    await step('generate + install a postgres + tenancy app', () => {
      app = generateApp('tenant-app', [
        '--preset', 'api', '--db', 'postgres', '--auth', 'email', '--tenancy',
        '--no-docker', '--pm', 'pnpm', '--no-git', '--yes',
      ])
    })
    const dbEnv = (user, password) => ({
      DB_HOST: '127.0.0.1', DB_PORT: String(port), DB_DATABASE: 'app', DB_USERNAME: user,
      DB_PASSWORD: password, DB_SSL: 'false',
    })
    await step('make:model Invoice (tenant-scoped) and a policy for tenant owners', () => {
      sv(app, ['make:model', 'Invoice', 'number:string:unique', 'amount:decimal(12,2)',
        'status:enum(draft,sent,paid):default(draft)'])
      const model = readFileSync(join(app, 'app/models/invoice.model.ts'), 'utf8')
      assert(model.includes('tenant: true'), 'model is tenant-scoped in a tenancy app')
      const policy = join(app, 'app/policies/invoice.policy.ts')
      writeFileSync(policy, readFileSync(policy, 'utf8').replace(/role: (\[[^\]]*\]|'[^']*')/g, "role: ['owner', 'admin', 'member']"))
    })
    await step('migrate as the owner; RLS enabled + forced on the tenant table', () => {
      sv(app, ['migrate'], { env: dbEnv('postgres', pgPassword) })
      const rls = psql("SELECT relrowsecurity::text || relforcerowsecurity::text FROM pg_class WHERE relname = 'invoices'")
      assert(rls === 'truetrue', `RLS enabled and forced (got ${rls})`)
      psql(`CREATE ROLE sv_runtime LOGIN PASSWORD '${runtimePassword}' NOSUPERUSER NOBYPASSRLS`)
      psql('GRANT USAGE ON SCHEMA public TO sv_runtime')
      psql('GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO sv_runtime')
    })
    const server = await startServer(app, 'start', {
      ...dbEnv('sv_runtime', runtimePassword),
      AUTH_ALLOW_REGISTRATION: 'true',
    })
    try {
      const api = '/api/v1'
      const tenantUser = async (email, slug) => {
        const c = client(server.base)
        assert((await c.call('POST', `${api}/auth/sign-up`, { email, password: secret(), name: slug })).status === 201, 'sign-up')
        const t = await c.call('POST', `${api}/auth/tenants`, { name: slug, slug })
        assert(t.status === 201, `create tenant (${t.text.slice(0, 200)})`)
        const s = await c.call('POST', `${api}/auth/switch-tenant`, { tenantId: t.json.tenantId })
        assert(s.status === 200 && s.json.actor.tenantId === t.json.tenantId, 'switched tenant')
        return { c, tenantId: t.json.tenantId }
      }
      let a
      let b
      await step('two users each create and switch to their own tenant', async () => {
        a = await tenantUser('a@acme.test', 'acme')
        b = await tenantUser('b@globex.test', 'globex')
      })
      await step('tenant scoping over HTTP: B never sees or reaches A\'s rows', async () => {
        const created = await a.c.call('POST', `${api}/invoices`, { number: 'A-1', amount: '5.00' })
        assert(created.status === 201, `A creates (${created.text.slice(0, 300)})`)
        assert((await a.c.call('GET', `${api}/invoices`)).json.data.length === 1, 'A sees 1')
        assert((await b.c.call('GET', `${api}/invoices`)).json.data.length === 0, 'B sees 0')
        assert((await b.c.call('GET', `${api}/invoices/${created.json.id}`)).status === 404, 'B gets 404')
        const forged = await b.c.call('GET', `${api}/invoices`, undefined, { 'x-tenant-id': a.tenantId })
        // The session's tenant wins over the header; a non-member header is refused outright.
        // Either way, A's rows must never come back.
        const leaked = forged.status === 200 && forged.json.data.some((r) => r.id === created.json.id)
        assert(forged.status === 403 || (forged.status === 200 && !leaked), `X-Tenant-Id cannot reach A (${forged.status})`)
        const headerOnly = client(server.base)
        await headerOnly.call('POST', `${api}/auth/sign-up`, { email: 'c@initech.test', password: secret(), name: 'c' })
        const noTenant = await headerOnly.call('GET', `${api}/invoices`, undefined, { 'x-tenant-id': a.tenantId })
        assert(noTenant.status === 403, `a non-member selecting A by header is refused (${noTenant.status})`)
        const sameNumber = await b.c.call('POST', `${api}/invoices`, { number: 'A-1', amount: '1.00' })
        assert(sameNumber.status === 201, 'unique is per tenant')
      })
      await step('RLS: the runtime role sees no rows without a tenant set', () => {
        assert(psql('SELECT count(*) FROM invoices', 'postgres') === '2', 'owner sees both')
        assert(psql('SELECT count(*) FROM invoices', 'sv_runtime') === '0', 'runtime role sees none')
        // Two statements: a set_config() in the same SELECT would run after the scan.
        const scoped = psql(`SET app.tenant_id = '${a.tenantId}'; SELECT count(*) FROM invoices`, 'sv_runtime')
        assert(scoped.split(/\s+/).at(-1) === '1', `runtime role sees only tenant A's row (${scoped})`)
      })
    } finally {
      await stopServer(server)
    }
  } finally {
    spawnSync('docker', ['rm', '-f', container], { stdio: 'ignore' })
  }
}

async function main() {
  const args = parseArgs(process.argv.slice(2))
  const started = Date.now()
  try {
    if (!args.skipBuild) await step('build every package', buildPackages)
    await sqliteJourney()
    if (!args.skipTenancy) await tenancyJourney()
    log(`\n✔ ${results.length} steps passed in ${Math.round((Date.now() - started) / 1000)} s`)
  } catch (error) {
    log(`\n✖ FAILED after ${results.filter((r) => r.ok).length} passing steps`)
    log(error instanceof Error ? (error.stack ?? error.message) : String(error))
    process.exitCode = 1
  }
}

